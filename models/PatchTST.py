    print("="*50)
    print("PatchTST 多任务模型初始化与流向测试...")

    # 1. 伪造 configs 对象
    class Config:
        def __init__(self):
            # 基础任务参数
            self.task_name = 'long_term_forecast'  
            self.seq_len = 96        
            self.pred_len = 720      
            self.enc_in = 7          
            
            # Transformer 结构参数
            self.d_model = 128       
            self.dropout = 0.1
            self.factor = 3
            self.n_heads = 4
            self.d_ff = 256
            self.activation = 'gelu'
            self.e_layers = 3
            
            # 分类任务独有参数
            self.num_class = 3       

    configs = Config()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ==========================================
    # 测试 A：长期预测任务 (Long-term Forecast)
    # ==========================================
    model_forecast = Model(configs, patch_len=16, stride=8).to(device)

    batch_size = 32
    mark_dim = 4 # 占位符，PatchTST 实际不使用 mark

    x_enc = torch.randn(batch_size, configs.seq_len, configs.enc_in).to(device)
    x_mark_enc = torch.zeros(batch_size, configs.seq_len, mark_dim).to(device)
    x_dec = torch.zeros(batch_size, configs.pred_len, configs.enc_in).to(device)
    x_mark_dec = torch.zeros(batch_size, configs.pred_len, mark_dim).to(device)

    print("\n[测试 A: 长期预测 (Forecasting)]")
    print(f"输入 x_enc -> {x_enc.shape}  # [Batch, seq_len, enc_in]")

    model_forecast.eval()
    with torch.no_grad():
        out_forecast = model_forecast(x_enc, x_mark_enc, x_dec, x_mark_dec)

    print(f"输出 out_forecast -> {out_forecast.shape}  # [Batch, pred_len, enc_in]")
    assert out_forecast.shape == (batch_size, configs.pred_len, configs.enc_in)
    print("✅ 预测流向测试通过！")
